"""Writes installer/Native/shipped_history.h: every path the published setups of earlier releases installed, per platform, and
each release's game executable SHA-256 (docs/installer.md, "Updating an install").

An update removes the program files the new version no longer ships. The install's own manifest names them; this list is the
fallback for an install whose manifest is missing (a portable copy, a manifest lost) and the safety net for files an older
update left behind. It holds only paths a release package shipped, never anything a player adds.


Each argument is a version, or version=folder when the folder under --releases has another name. The folder holds the published
P.T.PC.Port.Setup.exe and P.T.PC.Port.Setup-linux (check them against the GitHub release's asset digests first).
"""
from __future__ import annotations

import argparse
import hashlib
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from payload_index import payload_index  # noqa: E402

REPO = pathlib.Path(__file__).resolve().parents[2]
SETUPS = {"windows": ("P.T.PC.Port.Setup.exe", "pt.exe"), "linux": ("P.T.PC.Port.Setup-linux", "pt")}


def sha256(path: pathlib.Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def literal(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--releases", type=pathlib.Path, required=True)
    p.add_argument("--out", type=pathlib.Path, default=REPO / "installer" / "Native" / "shipped_history.h")
    p.add_argument("versions", nargs="+")
    a = p.parse_args()
    paths: dict[str, set[str]] = {platform: set() for platform in SETUPS}
    releases: dict[str, list[tuple[str, str, int]]] = {platform: [] for platform in SETUPS}
    for item in a.versions:
        version, _, folder = item.partition("=")
        folder = a.releases / (folder or version)
        for platform, (setup_name, exe) in SETUPS.items():
            setup = folder / setup_name
            if not setup.is_file():
                sys.exit(f"{setup} is missing")
            entries = payload_index(setup)
            names = {e["path"] for e in entries}
            paths[platform] |= names
            game = next((e for e in entries if e["path"] == exe), None)
            if game is None:
                sys.exit(f"{setup}: no {exe} in its payload")
            releases[platform].append((version, game["sha256"], len(entries)))
            print(f"{version} {platform}: {len(entries)} files ({sha256(setup)[:16]}...)")
    lines = [
        "#pragma once",
        "// Generated by tools/ci/shipped_history.py from the published setups; do not edit. Every path an earlier release's setup",
        "// installed, per platform, and each release's game executable (docs/installer.md, \"Updating an install\").",
        "namespace pt::setup::history {",
        "struct Release {",
        "    const char* version;",
        "    const char* game_sha256;  // pt.exe (Windows) or pt (Linux) of that release",
        "    int files;                // how many files its setup installed",
        "};",
    ]
    for platform in SETUPS:
        name = platform.capitalize()
        lines.append(f"inline constexpr Release k{name}Releases[] = {{")
        lines += [f"    {{{literal(v)}, {literal(s)}, {n}}}," for v, s, n in releases[platform]]
        lines.append("};")
        lines.append(f"inline constexpr const char* k{name}Paths[] = {{")
        lines += [f"    {literal(path)}," for path in sorted(paths[platform])]
        lines.append("};")
    lines.append("}")
    a.out.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    print(f"{a.out}: {', '.join(f'{k} {len(v)} paths' for k, v in paths.items())}")


if __name__ == "__main__":
    main()
